export function makeMap(map: MapId): Obstacle[] {
  const walls: [number, number, number, number][] =
    map === 'desert'
      ? [
          [-8, -9, 6, 2],
          [8, 9, 6, 2],
          [-9, 8, 2, 6],
          [9, -8, 2, 6],
          [-17, -7, 4, 2],
          [17, 7, 4, 2],
          [-6, 17, 2, 4],
          [6, -17, 2, 4],
          [-3, -3, 3, 2],
          [3, 3, 3, 2],
        ]
      : map === 'arctic'
        ? [
            [-9, -10, 2, 10],
            [9, 10, 2, 10],
            [-9, 10, 2, 10],
            [9, -10, 2, 10],
            [-16, 0, 3, 6],
            [16, 0, 3, 6],
            [0, 6, 7, 2],
            [0, -6, 7, 2],
          ]
        : [
            [-10, -10, 7, 2],
            [10, 10, 7, 2],
            [-10, 10, 2, 7],
            [10, -10, 2, 7],
            [-16, 5, 3, 3],
            [16, -5, 3, 3],
            [4, 16, 3, 3],
            [-4, -16, 3, 3],
            [-4, 0, 2, 5],
            [4, 0, 2, 5],
          ];
  const items: Obstacle[] = walls.map(([x, z, w, d], id) => ({
    id,
    x,
    z,
    w,
    d,
    h: 1.6 + (id % 3) * 0.35,
    hp: -1,
    kind: id % 4 === 3 ? 'rock' : 'wall',
  }));
  const crates = [
    [-5, -7],
    [5, 7],
    [-7, 4],
    [7, -4],
    [-14, 10],
    [14, -10],
    [-3, 13],
    [3, -13],
    [-12, -17],
    [12, 17],
    [-18, 13],
    [18, -13],
  ];
  crates.forEach(([x, z], i) => {
    if (!items.some((o) => Math.abs(o.x - x) < o.w / 2 + 1.2 && Math.abs(o.z - z) < o.d / 2 + 1.2))
      items.push({ id: 100 + i, x, z, w: 1.7, d: 1.7, h: 1.6, hp: 65, kind: 'crate' });
  });
  [
    [-5, 4],
    [5, -4],
    [-14, -4],
    [14, 4],
  ].forEach(([x, z], i) =>
    items.push({ id: 200 + i, x, z, w: 1, d: 1, h: 1.4, hp: 24, kind: 'barrel' }),
  );
  return items;
}
